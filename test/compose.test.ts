import { describe, expect, test } from "bun:test";
import { parse } from "yaml";
import {
  addInclude,
  hasInclude,
  removeInclude,
  renderService,
  renderSite,
  renderStaticDockerfile,
  STATIC_SERVER_IMAGE,
} from "../src/compose.ts";
import { parseConfig } from "../src/config.ts";

const fixture = (name: string) =>
  Bun.file(new URL(`fixtures/${name}`, import.meta.url)).text();

const worthy = parseConfig(
  {
    name: "worthy",
    domain: "worthy.jason0x43.dev",
    port: 3000,
    build: true,
    env: {
      NODE_ENV: "production",
      DATABASE_PATH: "/data/data.db",
    },
  },
  "/p",
);

describe("renderSite", () => {
  test("matches the hand-written reverse proxy snippet", async () => {
    expect(renderSite(worthy)).toBe(await fixture("worthy.caddy"));
  });

  test("proxies static sites to their static-web-server container", () => {
    const config = parseConfig(
      { name: "tmpdir-dev", domain: "tmpdir.dev", static: "dist" },
      "/p",
    );
    expect(renderSite(config)).toBe(
      "http://tmpdir.dev {\n\treverse_proxy tmpdir-dev:8080\n}\n",
    );
  });

  test("joins domains and appends extra directives", () => {
    const config = parseConfig(
      {
        name: "app",
        domain: ["a.tmpdir.dev", "b.tmpdir.dev"],
        port: 80,
        image: "nginx",
        caddy: { extra: "encode zstd gzip\n  header -Server\n" },
      },
      "/p",
    );
    expect(renderSite(config)).toBe(
      "http://a.tmpdir.dev, http://b.tmpdir.dev {\n\treverse_proxy app:80\n\tencode zstd gzip\n\theader -Server\n}\n",
    );
  });
});

describe("renderService", () => {
  test("generates a hardened service on the server network", () => {
    const text = renderService(worthy);
    expect(text).toStartWith("# Generated by portal");
    expect(parse(text)).toEqual({
      services: {
        worthy: {
          image: "portal/worthy:latest",
          pull_policy: "never",
          restart: "unless-stopped",
          user: "1000:1000",
          env_file: [{ path: ".env", required: false }],
          environment: {
            NODE_ENV: "production",
            DATABASE_PATH: "/data/data.db",
          },
          volumes: ["./data:/data"],
          security_opt: ["no-new-privileges:true"],
          cap_drop: ["ALL"],
          networks: ["server"],
        },
      },
    });
  });

  test("merges compose overrides", () => {
    const config = parseConfig(
      {
        name: "app",
        domain: "app.tmpdir.dev",
        port: 3000,
        build: true,
        hardened: true,
        compose: {
          user: "0:0",
          volumes: ["./data:/data", "./uploads:/uploads"],
          healthcheck: { test: ["CMD", "true"] },
        },
      },
      "/p",
    );
    const service = parse(renderService(config)).services.app;
    expect(service.user).toBe("0:0");
    expect(service.volumes).toEqual(["./data:/data", "./uploads:/uploads"]);
    expect(service.healthcheck).toEqual({ test: ["CMD", "true"] });
    expect(service.read_only).toBe(true);
    expect(service.tmpfs).toEqual(["/tmp"]);
  });
});

describe("static sites", () => {
  const site = (staticValue: unknown) =>
    parseConfig({ name: "site", domain: "site.tmpdir.dev", static: staticValue }, "/p");

  test("run read-only with no data volume", () => {
    const service = parse(renderService(site("dist"))).services.site;
    expect(service.image).toBe("portal/site:latest");
    expect(service.read_only).toBe(true);
    expect(service.volumes).toBeUndefined();
    expect(service.tmpfs).toBeUndefined();
    expect(service.cap_drop).toEqual(["ALL"]);
  });

  test("bake content and a no-cache default into the image", () => {
    expect(renderStaticDockerfile(site("dist"))).toBe(
      [
        `FROM ${STATIC_SERVER_IMAGE}`,
        "COPY <<'TOML' /etc/static-web-server.toml",
        "[general]",
        "port = 8080",
        'root = "/public"',
        "cache-control-headers = false",
        "",
        "[advanced]",
        "",
        "[[advanced.headers]]",
        'source = "/**"',
        "[advanced.headers.headers]",
        'Cache-Control = "no-cache"',
        "TOML",
        "COPY site /public",
        "ENV SERVER_CONFIG_FILE=/etc/static-web-server.toml",
        "",
      ].join("\n"),
    );
  });

  test("add a fallback page and immutable globs after the default", () => {
    const dockerfile = renderStaticDockerfile(
      site({ dir: "dist", fallback: "/index.html", immutable: ["assets/**", "/_app/**"] }),
    );
    expect(dockerfile).toContain('page-fallback = "/public/index.html"');
    const sources = [...dockerfile.matchAll(/source = "([^"]+)"/g)].map((m) => m[1]);
    expect(sources).toEqual(["/**", "/assets/**", "/_app/**"]);
    expect(dockerfile.match(/immutable"/g)).toHaveLength(2);
  });
});

describe("include editing", () => {
  test("appends to the real root compose file without reformatting it", async () => {
    const src = await fixture("root-compose.yaml");
    const out = addInclude(src, "services/app/compose.yaml")!;
    expect(out).toBe(
      src.replace(
        "  - services/worthy/compose.yaml\n",
        "  - services/worthy/compose.yaml\n  - services/app/compose.yaml\n",
      ),
    );
    expect(hasInclude(out, "services/app/compose.yaml")).toBe(true);
  });

  test("is a no-op when already included", async () => {
    const src = await fixture("root-compose.yaml");
    expect(addInclude(src, "services/worthy/compose.yaml")).toBeUndefined();
  });

  test("round-trips add and remove", async () => {
    const src = await fixture("root-compose.yaml");
    const added = addInclude(src, "services/app/compose.yaml")!;
    expect(removeInclude(added, "services/app/compose.yaml")).toBe(src);
    expect(removeInclude(src, "services/app/compose.yaml")).toBeUndefined();
  });

  test("removes an item from the middle of the list", async () => {
    const src = await fixture("root-compose.yaml");
    const out = removeInclude(src, "services/spellingbeeplus/compose.yaml")!;
    expect(out).not.toContain("spellingbeeplus");
    expect(parse(out).include).toEqual([
      "services/rvc-tmpdir-dev/compose.yaml",
      "services/worthy/compose.yaml",
    ]);
  });

  test("recognizes long-form include entries", () => {
    const src = "include:\n  - path: services/app/compose.yaml\n";
    expect(hasInclude(src, "services/app/compose.yaml")).toBe(true);
  });

  test("creates the include list when missing", () => {
    const src = "name: server\n\nservices:\n  caddy:\n    image: caddy\n";
    const out = addInclude(src, "services/app/compose.yaml")!;
    expect(parse(out)).toMatchObject({
      name: "server",
      include: ["services/app/compose.yaml"],
      services: { caddy: { image: "caddy" } },
    });
  });
});
