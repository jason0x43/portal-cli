import { Document, Scalar, visit } from "yaml";
import { isRecord, type Config } from "./config.ts";

export const NETWORK = "server";
export const DEFAULT_USER = "1000:1000";

export function imageRepo(name: string): string {
  return `portal/${name}`;
}

/**
 * Container label holding the configured image reference, since the image
 * itself only keeps its portal/<name> tags once it's retagged.
 */
export const IMAGE_LABEL = "portal.image";

/**
 * Standard OCI image label naming the image a build started from. Built
 * service images should set it so `portal update` can check their base.
 */
export const BASE_IMAGE_LABEL = "org.opencontainers.image.base.name";

/**
 * Standard OCI image label with the digest of the base image a build started
 * from, so a rebuilt tag such as debian:trixie-slim can be noticed.
 */
export const BASE_DIGEST_LABEL = "org.opencontainers.image.base.digest";

export function servicePath(name: string): string {
  return `services/${name}/compose.yaml`;
}

/** Render services/<name>/compose.yaml, a standalone compose project. */
export function renderService(config: Config): string {
  const isStatic = config.source.kind === "static";
  const base: Record<string, unknown> = {
    image: `${imageRepo(config.name)}:latest`,
    // Images are loaded or retagged by portal; never try to pull portal/*
    pull_policy: "never",
    restart: "unless-stopped",
    user: DEFAULT_USER,
    env_file: [{ path: ".env", required: false }],
    ...(Object.keys(config.env).length > 0 && { environment: config.env }),
    // Static sites have their content in the image and never write
    ...(!isStatic && { volumes: ["./data:/data"] }),
    security_opt: ["no-new-privileges:true"],
    cap_drop: ["ALL"],
    ...(isStatic
      ? { read_only: true }
      : config.hardened && { read_only: true, tmpfs: ["/tmp"] }),
    networks: [NETWORK],
    // The local driver rotates and compresses logs (5 x 20MB by default).
    // The default json-file driver grows without limit.
    logging: { driver: "local" },
    // Lets `portal update` look for newer versions of a pinned image
    ...(config.source.kind === "image" && {
      labels: { [IMAGE_LABEL]: config.source.image },
    }),
  };

  const service = deepMerge(base, config.compose);
  // Each service is its own compose project, so deploys never touch the
  // shared root compose file. They join the network the root project creates.
  const doc = new Document({
    name: config.name,
    services: { [config.name]: { container_name: config.name, ...service } },
    networks: { [NETWORK]: { external: true } },
  });
  doc.commentBefore = ` Generated by portal from ${config.name}'s portal.toml. Changes here are overwritten on deploy.`;
  // Quote values like 1000:1000, which YAML 1.1 parsers read as base-60 numbers
  visit(doc, {
    Scalar(_key, node) {
      if (typeof node.value === "string" && node.value.includes(":")) {
        node.type = Scalar.QUOTE_DOUBLE;
      }
    },
  });
  return doc.toString({ lineWidth: 0 });
}

/**
 * Merge `override` into `base`. Tables merge recursively, arrays are
 * concatenated without duplicates, and anything else replaces the base value.
 */
export function deepMerge(
  base: Record<string, unknown>,
  override: Record<string, unknown>,
): Record<string, unknown> {
  const out: Record<string, unknown> = { ...base };
  for (const [key, value] of Object.entries(override)) {
    const existing = out[key];
    if (isRecord(existing) && isRecord(value)) {
      out[key] = deepMerge(existing, value);
    } else if (Array.isArray(existing) && Array.isArray(value)) {
      const seen = new Set(existing.map((v) => JSON.stringify(v)));
      out[key] = [
        ...existing,
        ...value.filter((v) => !seen.has(JSON.stringify(v))),
      ];
    } else {
      out[key] = value;
    }
  }
  return out;
}

export const STATIC_SERVER_IMAGE = "joseluisq/static-web-server:2.44.1";

/**
 * Dockerfile for a static site: the content baked into a static-web-server
 * image. HTML and other unhashed files are served with `no-cache` (browsers
 * keep a copy but revalidate it), since static-web-server's defaults would
 * cache them for up to a year and hide new deploys.
 *
 * Requests are logged at the info level, with the client IP that Caddy passes
 * in X-Real-IP (see renderSite).
 */
export function renderStaticDockerfile(config: Config): string {
  if (config.source.kind !== "static") {
    throw new Error("not a static source");
  }
  const { fallback, immutable } = config.source;
  const header = (source: string, value: string) =>
    [
      "",
      "[[advanced.headers]]",
      `source = ${JSON.stringify(source)}`,
      "[advanced.headers.headers]",
      `Cache-Control = ${JSON.stringify(value)}`,
    ].join("\n");

  const toml = [
    "[general]",
    `port = ${config.port}`,
    'root = "/public"',
    "cache-control-headers = false",
    'log-level = "info"',
    "log-x-real-ip = true",
    ...(fallback
      ? [`page-fallback = ${JSON.stringify(`/public/${fallback.replace(/^\/+/, "")}`)}`]
      : []),
    "",
    "[advanced]",
    // Later rules take precedence
    header("/**", "no-cache"),
    ...immutable.map((glob) =>
      header(`/${glob.replace(/^\/+/, "")}`, "public, max-age=31536000, immutable"),
    ),
  ].join("\n");

  return [
    `FROM ${STATIC_SERVER_IMAGE}`,
    `LABEL ${BASE_IMAGE_LABEL}=${JSON.stringify(STATIC_SERVER_IMAGE)}`,
    "COPY <<'TOML' /etc/static-web-server.toml",
    toml,
    "TOML",
    "COPY site /public",
    "ENV SERVER_CONFIG_FILE=/etc/static-web-server.toml",
    "",
  ].join("\n");
}

/**
 * Render caddy/sites/<name>.caddy. Every request reaches Caddy through
 * cloudflared, so X-Forwarded-For only ever holds the tunnel's address. The
 * client IP comes from Cloudflare's CF-Connecting-IP, passed on as X-Real-IP.
 * When that header is missing, Caddy drops X-Real-IP rather than forwarding a
 * client-supplied one.
 */
export function renderSite(config: Config): string {
  const address = config.domains.map((d) => `http://${d}`).join(", ");
  const body = [
    `reverse_proxy ${config.name}:${config.port} {`,
    "\theader_up X-Real-IP {http.request.header.CF-Connecting-IP}",
    "}",
  ];
  if (config.caddyExtra) {
    body.push(
      ...config.caddyExtra
        .trim()
        .split("\n")
        .map((l) => l.trim()),
    );
  }
  return `${address} {\n${body.map((l) => `\t${l}`).join("\n")}\n}\n`;
}

/**
 * The route a disabled service gets in place of `route`, its real one: the
 * same domains, answered with a 503.
 */
export function renderDisabledSite(route: string): string {
  const address = route.slice(0, route.indexOf("{")).trim();
  return `${address} {\n\trespond "Service Unavailable" 503\n}\n`;
}
