import {
  Document,
  isMap,
  isScalar,
  isSeq,
  parseDocument,
  Scalar,
  visit,
} from "yaml";
import { isRecord, type Config } from "./config.ts";

export const NETWORK = "server";
export const DEFAULT_USER = "1000:1000";

export function imageRepo(name: string): string {
  return `portal/${name}`;
}

export function servicePath(name: string): string {
  return `services/${name}/compose.yaml`;
}

/** Render services/<name>/compose.yaml for a container-based service. */
export function renderService(config: Config): string {
  const isStatic = config.source.kind === "static";
  const base: Record<string, unknown> = {
    image: `${imageRepo(config.name)}:latest`,
    // Images are loaded or retagged by portal; never try to pull portal/*
    pull_policy: "never",
    restart: "unless-stopped",
    user: DEFAULT_USER,
    env_file: [{ path: ".env", required: false }],
    ...(Object.keys(config.env).length > 0 && { environment: config.env }),
    // Static sites have their content in the image and never write
    ...(!isStatic && { volumes: ["./data:/data"] }),
    security_opt: ["no-new-privileges:true"],
    cap_drop: ["ALL"],
    ...(isStatic
      ? { read_only: true }
      : config.hardened && { read_only: true, tmpfs: ["/tmp"] }),
    networks: [NETWORK],
  };

  const service = deepMerge(base, config.compose);
  const doc = new Document({ services: { [config.name]: service } });
  doc.commentBefore = ` Generated by portal from ${config.name}'s portal.toml. Changes here are overwritten on deploy.`;
  // Quote values like 1000:1000, which YAML 1.1 parsers read as base-60 numbers
  visit(doc, {
    Scalar(_key, node) {
      if (typeof node.value === "string" && node.value.includes(":")) {
        node.type = Scalar.QUOTE_DOUBLE;
      }
    },
  });
  return doc.toString({ lineWidth: 0 });
}

/**
 * Merge `override` into `base`. Tables merge recursively, arrays are
 * concatenated without duplicates, and anything else replaces the base value.
 */
export function deepMerge(
  base: Record<string, unknown>,
  override: Record<string, unknown>,
): Record<string, unknown> {
  const out: Record<string, unknown> = { ...base };
  for (const [key, value] of Object.entries(override)) {
    const existing = out[key];
    if (isRecord(existing) && isRecord(value)) {
      out[key] = deepMerge(existing, value);
    } else if (Array.isArray(existing) && Array.isArray(value)) {
      const seen = new Set(existing.map((v) => JSON.stringify(v)));
      out[key] = [
        ...existing,
        ...value.filter((v) => !seen.has(JSON.stringify(v))),
      ];
    } else {
      out[key] = value;
    }
  }
  return out;
}

export const STATIC_SERVER_IMAGE = "joseluisq/static-web-server:2.44.1";

/**
 * Dockerfile for a static site: the content baked into a static-web-server
 * image. HTML and other unhashed files are served with `no-cache` (browsers
 * keep a copy but revalidate it), since static-web-server's defaults would
 * cache them for up to a year and hide new deploys.
 */
export function renderStaticDockerfile(config: Config): string {
  if (config.source.kind !== "static") {
    throw new Error("not a static source");
  }
  const { fallback, immutable } = config.source;
  const header = (source: string, value: string) =>
    [
      "",
      "[[advanced.headers]]",
      `source = ${JSON.stringify(source)}`,
      "[advanced.headers.headers]",
      `Cache-Control = ${JSON.stringify(value)}`,
    ].join("\n");

  const toml = [
    "[general]",
    `port = ${config.port}`,
    'root = "/public"',
    "cache-control-headers = false",
    ...(fallback
      ? [`page-fallback = ${JSON.stringify(`/public/${fallback.replace(/^\/+/, "")}`)}`]
      : []),
    "",
    "[advanced]",
    // Later rules take precedence
    header("/**", "no-cache"),
    ...immutable.map((glob) =>
      header(`/${glob.replace(/^\/+/, "")}`, "public, max-age=31536000, immutable"),
    ),
  ].join("\n");

  return [
    `FROM ${STATIC_SERVER_IMAGE}`,
    "COPY <<'TOML' /etc/static-web-server.toml",
    toml,
    "TOML",
    "COPY site /public",
    "ENV SERVER_CONFIG_FILE=/etc/static-web-server.toml",
    "",
  ].join("\n");
}

/** Render caddy/sites/<name>.caddy. */
export function renderSite(config: Config): string {
  const address = config.domains.map((d) => `http://${d}`).join(", ");
  const body = [`reverse_proxy ${config.name}:${config.port}`];
  if (config.caddyExtra) {
    body.push(
      ...config.caddyExtra
        .trim()
        .split("\n")
        .map((l) => l.trim()),
    );
  }
  return `${address} {\n${body.map((l) => `\t${l}`).join("\n")}\n}\n`;
}

function includePaths(src: string) {
  const doc = parseDocument(src);
  if (doc.errors.length > 0) {
    throw new Error(`can't parse root compose.yaml: ${doc.errors[0]!.message}`);
  }
  const include = doc.get("include", true);
  if (include !== undefined && !isSeq(include)) {
    throw new Error("root compose.yaml has a non-list include");
  }
  return { include, items: include?.items ?? [] };
}

function itemPath(item: unknown): string | undefined {
  if (isScalar(item)) {
    return String(item.value);
  }
  if (isMap(item)) {
    const path = item.get("path");
    return typeof path === "string" ? path : undefined;
  }
}

export function hasInclude(src: string, path: string): boolean {
  return includePaths(src).items.some((item) => itemPath(item) === path);
}

/**
 * Add `path` to the root compose file's include list. Edits the text directly
 * rather than re-serializing, so the rest of the file keeps its formatting.
 * Returns undefined if the path is already included.
 */
export function addInclude(src: string, path: string): string | undefined {
  const { include, items } = includePaths(src);
  if (items.some((item) => itemPath(item) === path)) {
    return;
  }

  const last = items.at(-1) as { range?: [number, number, number] } | undefined;
  if (include && last?.range) {
    const lineStart = src.lastIndexOf("\n", last.range[0]) + 1;
    const indent = /^\s*/.exec(src.slice(lineStart))![0];
    const lineEnd = src.indexOf("\n", last.range[1]);
    const at = lineEnd === -1 ? src.length : lineEnd;
    return `${src.slice(0, at)}\n${indent}- ${path}${src.slice(at)}`;
  }

  if (include) {
    // An empty list, e.g. `include: []`
    throw new Error("can't add to an empty inline include list; edit it by hand");
  }

  // No include key: add one after the `name:` line, or at the top.
  const nameMatch = /^name:.*\n/m.exec(src);
  const at = nameMatch ? nameMatch.index + nameMatch[0].length : 0;
  const block = `${nameMatch ? "\n" : ""}include:\n  - ${path}\n${nameMatch ? "" : "\n"}`;
  return src.slice(0, at) + block + src.slice(at);
}

/**
 * Remove `path` from the root compose file's include list. Returns undefined if
 * it wasn't included.
 */
export function removeInclude(src: string, path: string): string | undefined {
  const { items } = includePaths(src);
  const item = items.find((i) => itemPath(i) === path) as
    | { range?: [number, number, number] }
    | undefined;
  if (!item?.range) {
    return;
  }
  const lineStart = src.lastIndexOf("\n", item.range[0]) + 1;
  const lineEnd = src.indexOf("\n", item.range[1]);
  return src.slice(0, lineStart) + src.slice(lineEnd === -1 ? src.length : lineEnd + 1);
}
